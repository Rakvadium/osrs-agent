"""Installs the /rs-* planning skills for Claude Code and/or Kiro.

Each installed skill is self-contained: its SKILL.md, plus the shared
procedure and gates files and the core/ scripts copied into it. Edit the
sources in skills/ and core/, then re-run this script.

  python install.py                     # Claude Code + Kiro, for your user (all projects)
  python install.py --tool claude       # just Claude Code
  python install.py --scope project     # into this repo's .claude/ and .kiro/ only
  python install.py --uninstall
"""
import argparse
import re
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SKILLS = ROOT / "skills"
SHARED = SKILLS / "shared"
CORE = ROOT / "core"
# Marks folders this script owns, so it never overwrites or deletes anything else.
MARKER = ".osrs-agent-installed"
TOOL_DIRS = {"claude": ".claude", "kiro": ".kiro"}


def skill_sources():
    return sorted(p for p in SKILLS.iterdir() if p.is_dir() and (p / "SKILL.md").exists())


def skill_md(source, tool):
    text = (source / "SKILL.md").read_text(encoding="utf-8")
    if tool == "kiro":
        # Claude Code-only frontmatter; Kiro follows the base Agent Skills spec.
        text = re.sub(r"^disable-model-invocation:.*\n", "", text, flags=re.M)
    return text


def install(target, tool):
    for source in skill_sources():
        dest = target / source.name
        if dest.exists():
            if not (dest / MARKER).exists():
                print("skip {}: exists and was not installed by this script".format(dest))
                continue
            shutil.rmtree(dest)
        (dest / "scripts").mkdir(parents=True)
        (dest / "SKILL.md").write_text(skill_md(source, tool), encoding="utf-8")
        for f in SHARED.glob("*.md"):
            shutil.copy2(f, dest / f.name)
        for f in CORE.glob("*.py"):
            shutil.copy2(f, dest / "scripts" / f.name)
        (dest / MARKER).write_text("Generated by {}. Edit the sources there.\n".format(ROOT / "install.py"), encoding="utf-8")
        print("installed {}".format(dest))


def uninstall(target):
    for source in skill_sources():
        dest = target / source.name
        if (dest / MARKER).exists():
            shutil.rmtree(dest)
            print("removed {}".format(dest))


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--tool", choices=["claude", "kiro", "all"], default="all")
    parser.add_argument("--scope", choices=["user", "project"], default="user")
    parser.add_argument("--uninstall", action="store_true")
    args = parser.parse_args()

    base = Path.home() if args.scope == "user" else ROOT
    for tool in (TOOL_DIRS if args.tool == "all" else [args.tool]):
        target = base / TOOL_DIRS[tool] / "skills"
        if args.uninstall:
            uninstall(target)
        else:
            target.mkdir(parents=True, exist_ok=True)
            install(target, tool)


if __name__ == "__main__":
    main()
